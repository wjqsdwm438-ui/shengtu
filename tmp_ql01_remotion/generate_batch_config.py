def main() -> None:
    base = Path(__file__).parent
    out = base / "src" / "ql-batch"
    out.mkdir(parents=True, exist_ok=True)

    records = []
    manifest = {"transparent": [], "checkerboards": []}
    for page_num, layers in PAGES:
        page = f"QL-{page_num:02d}"
        layer_records = []
        for index, (name, rects) in enumerate(layers, start=1):
            layer_records.append({
                "id": f"{page}-L{index:02d}",
                "name": name,
                "rects": [dict(x=x, y=y, width=w, height=h) for x, y, w, h in rects],
            })
            manifest["transparent"].append({
                "page": page,
                "filename": f"企业全流程_{page}_L{index:02d}_{name}_通道.png",
            })
        records.append({
            "page": page,
            "source": f"ql-batch/{page}.png",
            "layers": layer_records,
            **({
                "combinedRects": [
                    dict(x=x, y=y, width=w, height=h)
                    for x, y, w, h in COMBINED[page_num][0]
                ],
                "combinedFeathers": COMBINED[page_num][1],
            } if page_num in COMBINED else {}),
        })
        manifest["transparent"].append({
            "page": page,
            "filename": f"企业全流程_{page}_插图文字_通道合并版.png",
        })
        manifest["checkerboards"].append({
            "page": page,
            "filename": f"企业全流程_{page}_羽化棋盘审核图.png",
        })

    payload = json.dumps(records, ensure_ascii=False, indent=2)
    ts = (
        'import type {Rect} from "../ql01-pilot/feather-mask";\n\n'
        'export type LayerConfig = {readonly id: string; readonly name: string; readonly rects: readonly Rect[]};\n'
        'export type PageConfig = {readonly page: string; readonly source: string; readonly layers: readonly LayerConfig[]; readonly combinedRects?: readonly Rect[]; readonly combinedFeathers?: readonly number[]};\n\n'
        f'export const pageConfigs = {payload} as const satisfies readonly PageConfig[];\n'
    )
    (out / "page-config.ts").write_text(ts, encoding="utf-8")
    (base / "batch-manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"pages={len(records)} transparent={len(manifest['transparent'])} checkerboards={len(manifest['checkerboards'])}")


if __name__ == "__main__":
    main()
